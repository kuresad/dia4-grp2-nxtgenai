#!/usr/bin/env python3
"""TD 2 review of step 2: search the wrong consensus systematically instead of by hand.

Standard library only, no network. Reads `td1/traces-td1.csv`, keeps the last
attempt of each (run, model, question) cell, then prints in Markdown:

  1. every wrong value returned by at least two distinct models, within one run
     and across runs, with the runs of each model;
  2. the fixed 2-of-3 panel {gpt-oss-120b, north-mini-code, qwen3.8-27b} voted on
     EVERY combination of one run per member (4 x 2 x 5 = 40 combinations), per
     question: how many combinations give the right value, a wrong consensus or
     an abstention;
  3. for every wrong value 0, whether the population of the question's age filter
     is empty (a non-empty population means the 0 comes from the filter, not from
     the data).

    python td2/B-consensus/scan_shared_errors.py > td2/B-consensus/results/shared-errors.md
"""
import itertools
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "td2"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import REFERENCE, TRACES_ALL, load_vote, proposal_from_row, read_csv, reference_values  # noqa: E402
from probes import population_lines  # noqa: E402

PANEL = ["openai/gpt-oss-120b", "cohere/north-mini-code:free", "qwen/qwen3.8-27b"]


def short(model):
    return model.split("/")[-1].replace("-preview:free", "").replace(":free", "")


def main():
    rows = read_csv(TRACES_ALL)
    refs = reference_values(REFERENCE)
    vote = load_vote()
    last, runs_of = {}, defaultdict(list)
    for r in rows:
        last[(r["run_id"], r["model_requested"], r["case_id"])] = r
        if r["run_id"] not in runs_of[r["model_requested"]]:
            runs_of[r["model_requested"]].append(r["run_id"])

    shared = defaultdict(lambda: defaultdict(set))  # (case, value) -> model -> runs
    for (run, model, case), r in last.items():
        if r["verdict"] == "incorrect":
            shared[(case, int(r["value"]))][model].add(run)

    print("# Shared wrong values in the TD 1 traces (generated)\n")
    print("Source: `td1/traces-td1.csv`, last attempt per (run, model, question). Generated by "
          "`td2/B-consensus/scan_shared_errors.py`. Every run is real (`nature = real`); a combination "
          "across runs is an illustration, not a measured experiment.\n")
    print("## 1. Same wrong value from at least two distinct models\n")
    print("| question | wrong value | reference | models (runs) | same run? |")
    print("|---|---|---|---|---|")
    for (case, value), models in sorted(shared.items()):
        if len(models) < 2:
            continue
        common_runs = set.intersection(*models.values())
        cell = "; ".join(f"{short(m)} ({', '.join(sorted(r))})" for m, r in sorted(models.items()))
        print(f"| {case} | {value} | {refs[case]} | {cell} | "
              f"{'yes: ' + ', '.join(sorted(common_runs)) if common_runs else 'no'} |")

    print("\n## 2. The fixed 2-of-3 panel on every combination of runs\n")
    combos = list(itertools.product(*(runs_of[m] for m in PANEL)))
    print(f"{len(combos)} combinations: gpt-oss-120b {len(runs_of[PANEL[0]])} runs x north-mini-code "
          f"{len(runs_of[PANEL[1]])} x qwen3.8-27b {len(runs_of[PANEL[2]])}. Only the questions where at least "
          "one combination is not a correct consensus are listed.\n")
    print("| question | right | WRONG consensus | abstention | wrong value (combinations) |")
    print("|---|---|---|---|---|")
    total_wrong = 0
    for case in sorted(refs):
        right = wrong = abst = 0
        wrong_values = defaultdict(list)
        for combo in combos:
            members = []
            for model, run in zip(PANEL, combo):
                row = last.get((run, model, case)) or {"provider": "", "model_requested": model, "verdict": "absent"}
                members.append(proposal_from_row({**row, "provider": row["provider"] or model}))
            d = vote(members, 2)
            if not d["consensus"]:
                abst += 1
            elif d["value"] == refs[case]:
                right += 1
            else:
                wrong += 1
                wrong_values[d["value"]].append("+".join(combo))
        total_wrong += wrong
        if right < len(combos):
            detail = "; ".join(f"{v}: {', '.join(c)}" for v, c in wrong_values.items()) or "-"
            print(f"| {case} | {right} | {wrong} | {abst} | {detail} |")
    print(f"\nWrong consensus of the fixed panel: {total_wrong} of {len(combos) * len(refs)} "
          "(question x combination) decisions. None comes from a single run: see section 1.\n")

    print("## 3. Is a wrong 0 possible on the data?\n")
    print("A 0 is only a possible answer when no order line passes the filters. The probe counts the order "
          "lines of the reference query, re-executed read-only: if the reference is not 0, its population is "
          "not empty, so every 0 is refuted without knowing which model is right.\n")
    print("| question | models returning 0 | reference | order lines of the reference population |")
    print("|---|---|---|---|")
    for (case, value), models in sorted(shared.items()):
        if value == 0:
            print(f"| {case} | {', '.join(short(m) for m in sorted(models))} | {refs[case]} | "
                  f"{population_lines(case)} |")


if __name__ == "__main__":
    main()
