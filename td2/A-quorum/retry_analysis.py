#!/usr/bin/env python3
"""TD 2 review of step 1: the TD 1 retries, why they happened and what they do to the vote.

Standard library only, no network. Reads `td1/traces-td1.csv` (every attempt of every
run) and prints, in Markdown:

  1. per run: attempts, HTTP 429 answers, cells recovered by the single retry, cells
     still not executed after it;
  2. the quota named in the 429 messages (limit, used, requested) and the delay the
     skeleton waited before retrying;
  3. the pause between requests that the quota would have required, from the mean
     output tokens of the successful answers;
  4. the effect on the vote: a cell still `not_executed` is an unavailable member,
     which stays in n without a vote.

    python td2/A-quorum/retry_analysis.py > td2/A-quorum/results/retries.md
"""
import re
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "td2"))
from common import read_csv  # noqa: E402

QUOTA = re.compile(r"on (?P<kind>[^:]+?) \((?P<code>\w+)\): Limit (?P<limit>\d+), Used (?P<used>\d+), "
                   r"Requested (?P<requested>\d+)")
PAUSE_S = 3.0  # PAUSE_BETWEEN_REQUESTS_S of skeleton-multi-llm-en.py


def when(row):
    return datetime.fromisoformat(row["date_utc"])


def main():
    rows = read_csv(ROOT / "td1" / "traces-td1.csv")
    cells = defaultdict(list)  # (run, model, case) -> attempts in file order
    for r in rows:
        cells[(r["run_id"], r["model_requested"], r["case_id"])].append(r)

    print("# TD 1 retries (generated)\n")
    print("Source: `td1/traces-td1.csv`, every attempt. Generated by `td2/A-quorum/retry_analysis.py`. "
          "The skeleton retries a 429 once, after the `Retry-After` delay when it fits in 60 s, and never "
          "more than twice per cell across resumes.\n")
    print("## 1. Per run\n")
    print("| run | model | attempts | HTTP 429 answers | cells hit by a 429 | recovered by the retry | "
          "still not executed | first 429 at question |")
    print("|---|---|---|---|---|---|---|---|")
    runs = defaultdict(list)
    for key, attempts in cells.items():
        runs[(key[0], key[1])].append((key[2], attempts))
    lost = []
    for (run, model), items in runs.items():
        n_att = sum(len(a) for _, a in items)
        n429 = sum(r["http_status"] == "429" for _, a in items for r in a)
        hit = [(c, a) for c, a in items if any(r["http_status"] == "429" for r in a)]
        recovered = [c for c, a in hit if a[-1]["http_status"] == "200"]
        still = [c for c, a in items if a[-1]["verdict"] in ("not_executed", "access_error")]
        lost += [(run, model, c) for c in still]
        first = min((c for c, _ in hit), default="-")
        if n429:
            print(f"| {run} | {model.split('/')[-1]} | {n_att} | {n429} | {len(hit)} | {len(recovered)} | "
                  f"{' '.join(still) or 0} | {first} |")
    quiet = sorted({f"{run} ({model.split('/')[-1]})" for (run, model), items in runs.items()
                    if not any(r["http_status"] == "429" for _, a in items for r in a)})
    print(f"\nRuns without any 429: {', '.join(quiet)}.\n")

    print("## 2. The quota named by the provider, and the wait before the retry\n")
    quotas = defaultdict(list)
    waits = []
    for (run, model, case), attempts in cells.items():
        for i, r in enumerate(attempts):
            if r["http_status"] != "429":
                continue
            m = QUOTA.search(r["error"])
            if m:
                quotas[(model, m["code"], int(m["limit"]))].append((int(m["used"]), int(m["requested"])))
            if i + 1 < len(attempts):
                waits.append(((when(attempts[i + 1]) - when(r)).total_seconds(), attempts[i + 1]["http_status"]))
    print("| model | quota | limit | 429 answers | used when refused (min-max) | requested (min-max) |")
    print("|---|---|---|---|---|---|")
    for (model, code, limit), v in sorted(quotas.items()):
        print(f"| {model.split('/')[-1]} | {code} | {limit} | {len(v)} | {min(u for u, _ in v)}-{max(u for u, _ in v)} | "
              f"{min(q for _, q in v)}-{max(q for _, q in v)} |")
    ok_waits = [w for w, s in waits if s == "200"]
    ko_waits = [w for w, s in waits if s != "200"]
    print(f"\nWait before the retry: {len(ok_waits)} retries succeeded after "
          f"{min(ok_waits):.0f}-{max(ok_waits):.0f} s; {len(ko_waits)} retries got a second 429 after "
          f"{min(ko_waits):.0f}-{max(ko_waits):.0f} s.\n" if ko_waits else
          f"\nWait before the retry: {len(ok_waits)} retries, all succeeded.\n")

    print("## 3. The pause the quota required\n")
    print("| model | quota limit (output tokens / min) | mean output tokens of a successful answer | "
          "requests per minute at the kit pause (3 s) | output tokens per minute at that pace | "
          "pause needed between requests |")
    print("|---|---|---|---|---|---|")
    for (model, code, limit) in sorted(quotas):
        if code != "OTPM":
            continue
        outs = [int(r["tokens_completion"]) for r in rows
                if r["model_requested"] == model and r["http_status"] == "200" and r["tokens_completion"]]
        mean_out = sum(outs) / len(outs)
        latency = [int(float(r["latency_ms"])) / 1000 for r in rows
                   if r["model_requested"] == model and r["http_status"] == "200" and r["latency_ms"]]
        per_min = 60 / (PAUSE_S + sum(latency) / len(latency))
        print(f"| {model.split('/')[-1]} | {limit} | {mean_out:.0f} | {per_min:.1f} | {per_min * mean_out:.0f} | "
              f"{60 * mean_out / limit:.1f} s |")
    print("\nAt the kit pace qwen3.8-27b asks for more than twice its output-token quota, so the 429s from about "
          "the fifteenth question on were predictable, not random.\n")

    print("## 4. Effect on the vote\n")
    if lost:
        print("| run | model | question | final verdict | in the vote |")
        print("|---|---|---|---|---|")
        for run, model, case in sorted(lost):
            print(f"| {run} | {model.split('/')[-1]} | {case} | not_executed | unavailable member: stays in n, no vote |")
    print("\nIn the base batch every 429 was recovered by the retry, so the vote tables of step 1 contain no "
          "member made unavailable by the quota. In the repetitions D-paul-2 and D-kuresa-2 the retry came "
          "too early; a vote on those runs would have had qwen3.8-27b unavailable on these questions.")


if __name__ == "__main__":
    main()
