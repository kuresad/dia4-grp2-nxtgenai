#!/usr/bin/env python3
"""TD 2 step 3: the TD 1 evidence the routing rule cites, per question family.

Standard library only, no network. Reads `td1/traces-td1.csv` (all runs, every attempt),
keeps the last attempt of each (run, model, question) cell, and prints, per family
of the TD 2 statement and per model:

  - the base-batch result (one run per model, `in_base_batch = yes`), with the
    failing cells named `model:Cxx`;
  - the result of every run of that model (repetitions included), so that a
    model that is right once but unstable is visible.

    python td2/C-routing/family_evidence.py > td2/C-routing/results/family-evidence.md

The families follow `questions-td1.json` (`type` field); "completed age at a date"
is `age on a reference date`, "age at the order" is `age at the time of the order`,
"combinations" is every type containing a `+`.
"""
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "td2"))
from common import FAMILIES, load_vote, proposal_from_row, question_families, read_csv, reference_values  # noqa: E402

MODELS = ["openai/gpt-oss-20b", "openai/gpt-oss-120b", "qwen/qwen3.8-27b",
          "cohere/north-mini-code:free", "dots-studio/dots-3-note-preview:free"]
SHORT = {m: m.split("/")[1].replace("-preview:free", "").replace(":free", "") for m in MODELS}
PANELS = {  # distinct families only: gpt-oss, Cohere, Qwen, Dots
    "fixed {gpt-oss-120b, north-mini-code, qwen3.8-27b}":
        ["openai/gpt-oss-120b", "cohere/north-mini-code:free", "qwen/qwen3.8-27b"],
    "alt {gpt-oss-20b, qwen3.8-27b, dots-3-note}":
        ["openai/gpt-oss-20b", "qwen/qwen3.8-27b", "dots-studio/dots-3-note-preview:free"],
}


def main():
    family = question_families()
    cases = defaultdict(list)
    for case, fam in family.items():
        cases[fam].append(case)

    rows = read_csv(ROOT / "td1" / "traces-td1.csv")
    last, base_runs, run_order = {}, {}, {}
    provider = {r["model_requested"]: r["provider"] for r in rows}  # read from the traces, not guessed
    for r in rows:  # file order = attempt order inside each run
        last[(r["run_id"], r["model_requested"], r["case_id"])] = r
        run_order.setdefault(r["model_requested"], [])
        if r["run_id"] not in run_order[r["model_requested"]]:
            run_order[r["model_requested"]].append(r["run_id"])
        if r["in_base_batch"] == "yes":
            base_runs[r["model_requested"]] = r["run_id"]

    def score(run, model, ids):
        ok = [c for c in ids if (run, model, c) in last and last[(run, model, c)]["verdict"] == "correct"]
        bad = [f"{c}({last[(run, model, c)]['verdict']})" if (run, model, c) in last else f"{c}(not run)"
               for c in ids if c not in ok]
        return len(ok), bad

    print("# TD 1 evidence per question family (generated)\n")
    print("Source: `td1/traces-td1.csv`, last attempt per (run, model, question). Generated by "
          "`td2/C-routing/family_evidence.py`. Cell ids are `model:Cxx`, as in "
          "`td1/model-question-comparison-en_J.csv` (`cell_id`). Twenty questions and a handful of runs: "
          "a batch-specific observation, not an error rate.\n")
    for fam in FAMILIES:
        ids = cases[fam]
        print(f"## {fam} ({len(ids)}: {' '.join(ids)})\n")
        print("| model | base batch | failing base cells | every run (correct/total) |")
        print("|---|---|---|---|")
        for m in MODELS:
            ok, bad = score(base_runs[m], m, ids)
            runs = "; ".join(f"{run} {score(run, m, ids)[0]}/{len(ids)}" for run in run_order[m])
            print(f"| {SHORT[m]} | {ok}/{len(ids)} ({base_runs[m]}) | "
                  f"{' '.join(f'{SHORT[m]}:{b}' for b in bad) or '-'} | {runs} |")
        print()

    # Candidate 2-of-3 panels, voted with the group's vote_k_sur_n (no network).
    vote = load_vote()
    refs = reference_values(ROOT / "td1" / "reference-td1.csv")

    def proposals(panel, case, source):
        out = []
        for m in panel:
            run = base_runs[m] if source == "base" else "FULL-1"
            # A missing cell is an unavailable member: it keeps its place in n.
            r = last.get((run, m, case)) or {"provider": provider[m], "model_requested": m, "verdict": "absent"}
            out.append(proposal_from_row(r))
        return out

    print("## Candidate 2-of-3 panels per family (vote_k_sur_n, k=2, n=3)\n")
    print("`base` = each member's base-batch run; `FULL-1` = the single run where the five models answered "
          "the same prompt in the same session. right = consensus equal to the reference; wrong = consensus "
          "on another value; abst = abstention.\n")
    print("| family | panel | base: right / wrong / abst | FULL-1: right / wrong / abst | wrong or abstained cells |")
    print("|---|---|---|---|---|")
    for fam in FAMILIES:
        for name, panel in PANELS.items():
            cells, tally = [], {}
            for source in ("base", "FULL-1"):
                t = [0, 0, 0]
                for c in cases[fam]:
                    d = vote(proposals(panel, c, source), 2)
                    if not d["consensus"]:
                        t[2] += 1; cells.append(f"{source}:{c} abst")
                    elif d["value"] == refs[c]:
                        t[0] += 1
                    else:
                        t[1] += 1; cells.append(f"{source}:{c} WRONG {d['value']}")
                tally[source] = "/".join(map(str, t))
            print(f"| {fam} | {name} | {tally['base']} | {tally['FULL-1']} | {' ; '.join(cells) or '-'} |")
    print()


if __name__ == "__main__":
    main()
